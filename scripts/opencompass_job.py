"""Run Artificial Analysis's tests through OpenCompass on the lab's engines.

The campaign runner starts this for jobs with ``kind: opencompass``. Two
phases, so the judge model never shares GPUs with the model under test:

- ``phase: infer``: launch the model exactly as a capacity job would (same
  image, flags and tuned overrides), collect answers for each test, shut the
  engine down. Summary status is ok when every test has all its answers.
- ``phase: judge``: launch the judge model, then grade each listed infer
  job's answers (OpenCompass ``-m eval`` on that job's work dir). Summary
  status is ok when every listed job has a score for every judged test.

Tests (``opencompass.tests``):
  hle          HLE, 2,158 text-only questions, official prompts and judge.
  aa_lcr       AA-LCR v1.1, 100 questions x 3, OpenCompass's AA config.
  omniscience  AA-Omniscience public v1.1 (300 of AA's 3,000 questions).

``opencompass.test_range`` (for a gate run) limits every test to a slice,
e.g. ``"[0:20]"``.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import pprint
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OC_ROOT = Path(os.environ.get("CAPSIM_OPENCOMPASS_ROOT", "/data/capsim-planner/opencompass"))
OC_BIN = OC_ROOT / "venv" / "bin" / "opencompass"
OC_COMMIT = "3ab1d83765580e437e1360b2409ca7381a7af9f2"
ADDINS = REPO / "scripts" / "oc"
REUSE = "capsim"  # fixed OpenCompass run folder, so the judge job finds the answers
TESTS = ("hle", "aa_lcr", "omniscience")


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def abbr(job: dict) -> str:
    return "capsim-" + job["id"].lower()


def work_dir(rundir: Path) -> Path:
    return rundir / "oc"


def config_text(job: dict, base_url: str, served: str, judge: dict | None = None) -> str:
    """The OpenCompass config for one infer job. ``judge`` (url and served
    model name) is filled in only when grading."""
    oc = job["opencompass"]
    tests = list(oc.get("tests") or TESTS)
    bad = [t for t in tests if t not in TESTS]
    if bad:
        raise ValueError(f"unknown tests {bad}; known: {TESTS}")
    settings = {
        "abbr": abbr(job),
        "served": served,
        "url": base_url.rstrip("/") + ("" if base_url.rstrip("/").endswith("/v1") else "/v1"),
        "max_seq_len": int(job.get("max_model_len") or 131072) - 512,
        "max_out_len": int(oc["max_tokens"]),
        "concurrency": int(oc.get("concurrency", 16)),
        "timeout_s": int(oc.get("timeout_s", 7200)),
        "sampling": {"temperature": float(oc["temperature"]),
                     **({"top_p": float(oc["top_p"])} if oc.get("top_p") is not None else {}),
                     **(oc.get("api_kwargs") or {})},
        "reasoning": bool(oc.get("reasoning", True)),
        "tests": tests,
        "test_range": oc.get("test_range"),
        "judge": judge,
        "hle_judge_prompt": _hle_judge_prompt(),
    }
    # A Python literal, not JSON: OpenCompass loads configs lazily, so a
    # config cannot call imported functions (json.loads) while loading.
    return CONFIG_TEMPLATE.replace("@@SETTINGS@@", pprint.pformat(settings, width=100, sort_dicts=False))


CONFIG_TEMPLATE = r'''# Generated by scripts/opencompass_job.py; do not edit.
from mmengine.config import read_base
from opencompass.models import OpenAISDK
from opencompass.partitioners import NaivePartitioner
from opencompass.runners import LocalRunner
from opencompass.tasks import OpenICLEvalTask, OpenICLInferTask
from opencompass.openicl.icl_raw_prompt_template import RawPromptTemplate
from opencompass.openicl.icl_retriever import ZeroRetriever
from opencompass.openicl.icl_inferencer import GenInferencer
from opencompass.evaluator import GenericLLMEvaluator

with read_base():
    from opencompass.configs.datasets.aa_lcr.aa_lcr_v1_1_gen import aa_lcr_v1_1_datasets
    from opencompass.configs.datasets.aa_omniscience.aa_omniscience_v1_1_llmjudge_rawprompt import \
        aa_omniscience_v1_1_datasets

S = @@SETTINGS@@

FINAL_MARK = '\n<<<capsim-final-answer>>>\n'

hle_reader_cfg = dict(input_columns=['system', 'question'], output_column='answer')
hle_datasets = [dict(
    type='HLEOfficialDataset', abbr='HLE-text', path='cais/hle',
    reader_cfg=hle_reader_cfg,
    infer_cfg=dict(
        prompt_template=dict(type=RawPromptTemplate, messages=[
            {'role': 'system', 'content': '{system}'},
            {'role': 'user', 'content': '{question}'}]),
        retriever=dict(type=ZeroRetriever),
        inferencer=dict(type=GenInferencer)),
    eval_cfg=dict(
        evaluator=dict(
            type=GenericLLMEvaluator,
            prompt_template=dict(type=RawPromptTemplate, messages=[
                {'role': 'user', 'content': S['hle_judge_prompt']}]),
            dataset_cfg=dict(type='HLEOfficialDataset', path='cais/hle', reader_cfg=hle_reader_cfg),
            judge_cfg=dict(),
            dict_postprocessor=dict(type='hle_official_judge_postprocess')),
        pred_role='BOT'),
)]

_by_test = {'hle': hle_datasets, 'aa_lcr': aa_lcr_v1_1_datasets, 'omniscience': aa_omniscience_v1_1_datasets}
datasets = []
for t in S['tests']:
    for d in _by_test[t]:
        if S['test_range']:
            d['reader_cfg'] = dict(d['reader_cfg'], test_range=S['test_range'])
            if 'dataset_cfg' in d['eval_cfg']['evaluator']:
                d['eval_cfg']['evaluator']['dataset_cfg']['reader_cfg'] = dict(d['reader_cfg'])
        datasets.append(d)

models = [dict(
    abbr=S['abbr'], type=OpenAISDK, path=S['served'], key='EMPTY',
    openai_api_base=S['url'], tokenizer_path='gpt-4o',
    max_seq_len=S['max_seq_len'], max_out_len=S['max_out_len'],
    batch_size=S['concurrency'], query_per_second=S['concurrency'],
    retry=3, timeout=S['timeout_s'], mode='none',
    think_tag=FINAL_MARK, openai_extra_kwargs=S['sampling'],
    pred_postprocessor=dict(type='capsim-final-answer') if S['reasoning'] else None,
    run_cfg=dict(num_gpus=0),
)]
if not S['reasoning']:
    models[0].pop('pred_postprocessor')

if S['judge']:
    judge_cfg = dict(
        abbr='judge', type=OpenAISDK, path=S['judge']['served'], key='EMPTY',
        openai_api_base=S['judge']['url'], tokenizer_path='gpt-4o',
        max_seq_len=32768, max_out_len=4096, temperature=0,
        batch_size=64, query_per_second=64, retry=3, timeout=1800, mode='none',
        extra_body={'chat_template_kwargs': {'enable_thinking': False}},
    )
    for d in datasets:
        ev = d['eval_cfg']['evaluator']
        if 'judge_cfg' in ev:
            ev['judge_cfg'] = judge_cfg
        if 'llm_evaluator' in ev and 'judge_cfg' in ev['llm_evaluator']:
            ev['llm_evaluator']['judge_cfg'] = judge_cfg

infer = dict(partitioner=dict(type=NaivePartitioner),
             runner=dict(type=LocalRunner, max_num_workers=len(datasets), task=dict(type=OpenICLInferTask)))
eval = dict(partitioner=dict(type=NaivePartitioner),
            runner=dict(type=LocalRunner, max_num_workers=len(datasets), task=dict(type=OpenICLEvalTask)))
'''


def _hle_judge_prompt() -> str:
    sys.path.insert(0, str(ADDINS))
    from hle_prompts import HLE_JUDGE_PROMPT
    return HLE_JUDGE_PROMPT


def write_config(job: dict, rundir: Path, base_url: str, served: str, judge: dict | None = None) -> Path:
    path = rundir / ("oc_config_judge.py" if judge else "oc_config.py")
    path.write_text(config_text(job, base_url, served, judge))
    return path


def oc_env() -> dict:
    env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "UV_PROJECT_ENVIRONMENT")}
    token = Path.home() / ".cache" / "huggingface" / "token"
    env.update(CAPSIM_OC="1", PYTHONPATH=str(ADDINS), HF_HOME=str(OC_ROOT / "hf"),
               COMPASS_DATA_CACHE=str(OC_ROOT / "data"),
               PATH=f"{OC_ROOT / 'venv' / 'bin'}:{env.get('PATH', '/usr/bin:/bin')}")
    if token.exists():
        env["HF_TOKEN"] = token.read_text().strip()
    return env


def run_oc(cfg: Path, mode: str, rundir: Path, log) -> int:
    cmd = [str(OC_BIN), str(cfg), "-m", mode, "-w", str(work_dir(rundir)), "-r", REUSE]
    log.write(f"{now()} opencompass: {' '.join(cmd)}\n"); log.flush()
    return subprocess.run(cmd, cwd=OC_ROOT, stdout=log, stderr=subprocess.STDOUT, env=oc_env()).returncode


def _preds(rundir: Path, job: dict) -> dict[str, list[str]]:
    """Answers per OpenCompass dataset abbreviation (repeats included)."""
    out: dict[str, list[str]] = {}
    pdir = work_dir(rundir) / REUSE / "predictions" / abbr(job)
    for f in sorted(pdir.glob("*.json")) if pdir.exists() else []:
        name = f.stem.split("_")[0] if f.stem.rsplit("_", 1)[-1].isdigit() else f.stem
        rows = json.loads(f.read_text())
        out.setdefault(name, []).extend(str(v.get("prediction", "")) for v in rows.values())
    return out


def answer_summary(rundir: Path, job: dict) -> dict:
    from_mark = "\n<<<capsim-final-answer>>>\n"
    per = {}
    for name, preds in _preds(rundir, job).items():
        cut = sum(1 for p in preds if from_mark not in p) if job["opencompass"].get("reasoning", True) else 0
        per[name] = {"answers": len(preds), "cut_off": cut, "cut_off_share": round(cut / max(1, len(preds)), 4)}
    return per


def scores(rundir: Path, job: dict) -> dict:
    out = {}
    rdir = work_dir(rundir) / REUSE / "results" / abbr(job)
    for f in sorted(rdir.glob("*.json")) if rdir.exists() else []:
        r = json.loads(f.read_text())
        out[f.stem] = {k: v for k, v in r.items() if k != "details" and not isinstance(v, (list, dict))}
    return out


def expected_tests(job: dict) -> list[str]:
    names = {"hle": "HLE-text", "aa_lcr": "AA-LCR-v1.1", "omniscience": "AA-Omniscience-Public-v1.1"}
    return [names[t] for t in (job["opencompass"].get("tests") or TESTS)]


def _engine(config: str, rundir: Path):
    sys.path.insert(0, str(REPO))
    from simulator.config import load_config
    from simulator.engines import make_engine
    cfg = load_config(config)
    return cfg, make_engine(cfg.engine.type, cfg.engine)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--job-file", required=True)
    ap.add_argument("--runs-dir", help="where infer jobs' run folders live (judge phase)")
    a = ap.parse_args(argv)
    job = json.loads(Path(a.job_file).read_text())
    rundir = Path(a.job_file).parent
    runs = Path(a.runs_dir) if a.runs_dir else rundir.parent
    log = open(rundir / "opencompass.log", "a")
    oc = job["opencompass"]
    phase = oc.get("phase", "infer")
    cfg, engine = _engine(a.config, rundir)
    manifest = {"job": job["id"], "phase": phase, "model": job["model"], "opencompass_commit": OC_COMMIT,
                "settings": oc, "engine": {"type": cfg.engine.type, "image": getattr(cfg.engine, "gpu_image", None),
                                           "max_model_len": getattr(cfg.engine, "max_model_len", None),
                                           "tp": getattr(cfg.engine, "tensor_parallel_size", None),
                                           "extra_flags": getattr(cfg.engine, "vllm_extra_flags", None)
                                           or getattr(cfg.engine, "sglang_extra_flags", None)},
                "started": now()}
    (rundir / "manifest.json").write_text(json.dumps(manifest, indent=1, default=str))
    summary: dict = {"status": "failed", "job": job["id"], "phase": phase}
    try:
        t0 = time.time()
        engine.launch()
        log.write(f"{now()} engine up in {time.time() - t0:.0f}s at {engine.base_url}\n"); log.flush()
        if phase == "infer":
            path = write_config(job, rundir, engine.base_url, engine.api_model_name)
            summary["rc"] = run_oc(path, "infer", rundir, log)
        else:
            judge = {"url": engine.base_url.rstrip("/") + ("" if engine.base_url.rstrip("/").endswith("/v1") else "/v1"),
                     "served": engine.api_model_name, "model": job["model"]}
            summary["graded"] = {}
            for jid in oc["grade"]:
                tdir = runs / jid
                tjob = json.loads((tdir / "job.json").read_text())
                path = write_config(tjob, tdir, "http://unused/v1", "unused", judge)
                rc = run_oc(path, "eval", tdir, log)
                sc = scores(tdir, tjob)
                (tdir / "opencompass_scores.json").write_text(json.dumps(
                    {"judge": judge, "rc": rc, "scores": sc, "answers": answer_summary(tdir, tjob),
                     "graded": now()}, indent=1))
                summary["graded"][jid] = {"rc": rc, "scores": sc}
    finally:
        engine.shutdown()
        log.write(f"{now()} engine down\n"); log.flush()
    if phase == "infer":
        per = answer_summary(rundir, job)
        summary["answers"] = per
        if summary.get("rc") == 0 and all(t in per and per[t]["answers"] > 0 for t in expected_tests(job)):
            summary["status"] = "ok"
    else:
        ok = True
        for jid, g in summary["graded"].items():
            tjob = json.loads((runs / jid / "job.json").read_text())
            ok &= g["rc"] == 0 and all(t in g["scores"] for t in expected_tests(tjob))
        if ok and summary["graded"]:
            summary["status"] = "ok"
    summary["finished"] = now()
    (rundir / "opencompass_summary.json").write_text(json.dumps(summary, indent=1))
    log.write(f"{now()} summary: {json.dumps(summary)[:4000]}\n")
    log.close()
    return 0 if summary["status"] == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())
