"""Token throughput and latency outputs share one measured curve table."""

import csv

from .workflow_report import render_outputs


def render(path, manifest, state, comparison):
    rows, flat = [], []
    for cell in state["results"]:
        for rung in cell["rungs"]:
            flat.append({k: v for k, v in cell.items() if k not in ("rungs", "peak")} | rung)
            rows.append(
                [
                    cell["shape"],
                    "Aggregate" if not cell["prefill"] else f"{cell['prefill']}P",
                    rung["concurrency"],
                    rung.get("out_tok_s"),
                    rung.get("ttft_p50_ms"),
                    rung.get("ttft_p95_ms"),
                    "Yes" if rung.get("steady_state") else "No",
                ]
            )
    if flat:
        with (path / "token-curves.csv").open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=sorted({k for r in flat for k in r}))
            writer.writeheader()
            writer.writerows(flat)
    peak = comparison.get("peak_uplift")
    latency = max(
        comparison.get("matched_concurrency_ttft", []),
        key=lambda x: x["reduction_percent"],
        default=None,
    )
    methods = [
        ("Instrument", manifest["harness"]),
        (
            "Workload",
            "Fixed token-shape synthetic generation, EOS ignored. Uses the same persona and load generator as roofline. Shape lengths are requested content lengths; template overhead and actual usage must be considered when matching historical measurements.",
        ),
        (
            "Throughput",
            "Native counter delta per measured second after consecutive stable chunks. Aggregate workers or decode workers supply output counters; prefill work is not double-counted. Includes reasoning tokens generated by the server; does not establish answer quality.",
        ),
        (
            "Comparators",
            "Same campaign, model revision, precision, workload and GPU budget. Best usable rung per shape compared across arms; equal concurrency latency is not equal arrival-rate latency. Historical entries are contextual until their entire measurement contract matches.",
        ),
        (
            "Search",
            str(manifest["spec"]["p01_token_shapes"])
            + "; streams "
            + str(manifest["spec"]["p01_streams"]),
        ),
        (
            "Reuse",
            "One launch per allocation; reuse completed shape sweeps during bounded same-allocation retries. No automatic reuse of incompatible historical measurements.",
        ),
        (
            "Evidence",
            "Full rung curves, runtime logs, native counter snapshots, transfer checks, topology, database and telemetry accompany the archive.",
        ),
        (
            "Limits",
            "Best observed exploratory points; no guarantee of global optimality. Excludes nonconverged rungs, fewer than 30 finished requests, over 1% failures, and incomplete metric scrapes from uplift ranking.",
        ),
    ]
    render_outputs(
        path,
        manifest,
        state,
        comparison,
        ["Shape", "Split", "Streams", "Output tok/s", "TTFT p50 ms", "TTFT p95 ms", "Stable"],
        rows,
        methods,
        [peak, latency, dict(measured_shapes=len(state["results"]), measured_rungs=len(flat))],
    )
